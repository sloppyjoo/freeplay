#!/usr/bin/env python3
"""Check cfw/presets/cc_presets.csv against a MIDI Guide checkout and write cfw/src/ccpresets.h.

usage: gen_cc_presets.py <path to a checkout of github.com/pencilresearch/midi>
Every "CC=parameter" must exist in that device's file with that CC number and exact parameter name."""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'presets', 'cc_presets.csv')
OUT = os.path.join(HERE, '..', 'src', 'ccpresets.h')


def main():
    db, bad, rows = sys.argv[1], 0, []
    for line in open(SRC, encoding='utf-8'):
        line = line.rstrip('\n')
        if not line or line.startswith('#'):
            continue
        f = line.split(';')
        if len(f) != 10:
            print('need 10 fields:', line)
            bad += 1
            continue
        known = set()
        with open(os.path.join(db, f[1] + '.csv'), encoding='utf-8', errors='replace') as fh:
            for r in csv.DictReader(fh):
                m = (r.get('cc_msb') or '').strip()
                if m.isdigit():
                    known.add((int(m), r['parameter_name'].strip()))
        vals = []
        for s in f[2:]:
            if s == '-':
                vals.append(255)
                continue
            cc, name = s.split('=', 1)
            if (int(cc), name) not in known:
                print(f'{f[0]}: not in the dataset: {s}')
                bad += 1
            vals.append(int(cc))
        rows.append((f[0], vals))
    if bad:
        raise SystemExit(f'{bad} problems')
    with open(OUT, 'w', encoding='utf-8') as o:
        o.write('/* Generated by cfw/tools/gen_cc_presets.py from cfw/presets/cc_presets.csv. CC numbers: MIDI Guide\n'
                ' * (github.com/pencilresearch/midi), CC BY-SA 4.0. 255 = leave the slot as it is. */\n')
        o.write('static const struct {\n    const char *name;\n    u8 cc[8];\n} cc_factory[] = {\n')
        for n, v in rows:
            o.write(f'    {{"{n}", {{{", ".join(map(str, v))}}}}},\n')
        o.write('};\n')
    print(len(rows), 'presets ok')


if __name__ == '__main__':
    main()
